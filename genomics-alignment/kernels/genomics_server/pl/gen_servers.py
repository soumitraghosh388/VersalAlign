#!/usr/bin/env python3
"""Generate the genomics_server RESIDENT PL server kernels.

Difference vs genomics_dma (per-launch):
  - Each server is launched ONCE and processes `nbatch` batches in an internal
    loop, synchronised with the host through a DDR "doorbell".
  - dist_server  polls ctrl_in[0] (a volatile m_axi word); when the host bumps
    it to b+1, dist streams batch b into the AIE array.
  - collect_server drains one batch off the 50 column streams, stores it, then
    bumps ctrl_out[0] = b+1 so the host knows batch b is done.

This eliminates the per-batch kernel-launch (ERT/XGQ scheduler) overhead of the
per-launch model: one launch serves nbatch batches; per batch the host pays only
a DDR doorbell write + a completion poll, not a scheduler round-trip.

Design choices (bring-up; see SERVER_NOTES.md):
  - FINITE loop bounded by the `nbatch` scalar arg (not while(1)): the kernels
    return after nbatch batches so run.wait() completes cleanly — no STOP-word
    teardown needed yet. True while(1) + STOP is a later step.
  - RING = 1 (no host/device overlap): the host fully serialises
    write-slot -> doorbell -> wait-completion -> read. Bump RING (and the host)
    to enable double-buffered overlap once correctness is proven.
  - doorbell pointers are `volatile` so HLS re-issues the m_axi read/write each
    pass instead of hoisting it. This volatile-polling loop is the #1 thing to
    validate on real hardware (csim cannot expose hoisting).

The PLIO is 32-bit (plio_32_bits), so the servers move int32 words to/from
32-bit AXIS streams — no 512->128 split needed (unlike GEMM's dma.cc).

Run:  python3 gen_servers.py    (regenerates the two .cpp files)
"""

NUM_ROWS = 8
NUM_COLS = 50
BUF_SIZE = 2048     # int32 per row input  (matches AIE input_async_buffer<int32>{128})
SCORE_BUF = 64    # int32 per column output (matches AIE scores_out{256})
RING = 2           # batch slots in DDR; 2 = double-buffer (H2D b+1 overlaps HW compute b)

HEADER = """// GENERATED by gen_servers.py — do not edit by hand.
// RESIDENT server: one launch processes `nbatch` batches via a DDR doorbell.
#include <ap_int.h>
#include <ap_axi_sdata.h>
#include <hls_stream.h>

typedef ap_axiu<32, 0, 0, 0> axis32_t;

#define BUF_SIZE  {buf}
#define SCORE_BUF {score}
#define NUM_ROWS  {rows}
#define NUM_COLS  {cols}
#define RING      {ring}
"""


def dist_server():
    s = HEADER.format(buf=BUF_SIZE, score=SCORE_BUF, rows=NUM_ROWS,
                      cols=NUM_COLS, ring=RING)
    s += """
// One m_axi reader: pull one batch (NUM_ROWS row sub-batches) into buffers.
static void load_all(const int *batch_slot, int buf[NUM_ROWS][BUF_SIZE]) {
    for (int r = 0; r < NUM_ROWS; r++)
        for (int i = 0; i < BUF_SIZE; i++) {
#pragma HLS pipeline II=1
            buf[r][i] = batch_slot[r * BUF_SIZE + i];
        }
}

// One sender per row: drain its buffer into its AIE input stream.
static void send_row(const int buf[BUF_SIZE], hls::stream<axis32_t> &s) {
    for (int i = 0; i < BUF_SIZE; i++) {
#pragma HLS pipeline II=1
        axis32_t x;
        x.data = buf[i];
        x.keep = -1;
        x.last = (i == BUF_SIZE - 1);
        s.write(x);
    }
}

// Process exactly one batch: load slot from DDR, fan out to the 8 row streams.
// The dataflow region lives here (one m_axi reader; each buf has 1 writer / 1
// reader) so it can be called once per batch from the resident loop.
static void process_batch(const int *batch_slot,
"""
    s += ",\n".join(f"                          hls::stream<axis32_t> &aie_in_{r}"
                    for r in range(NUM_ROWS))
    s += ") {\n#pragma HLS dataflow\n"
    s += "    int buf[NUM_ROWS][BUF_SIZE];\n"
    s += "#pragma HLS array_partition variable=buf dim=1 type=complete\n\n"
    s += "    load_all(batch_slot, buf);\n"
    for r in range(NUM_ROWS):
        s += f"    send_row(buf[{r}], aie_in_{r});\n"
    s += "}\n"

    s += """
// Doorbell: spin until the host has published batch `target` (ctrl_in[0] >= target).
// `ctrl_in` is volatile so HLS re-issues the m_axi read each pass (no hoisting).
static void wait_doorbell(volatile const int *ctrl_in, int target) {
wait_loop:
    while (ctrl_in[0] < target) {
#pragma HLS pipeline off
        ;
    }
}

extern "C" void dist_server(const int *batch_in,
                            volatile const int *ctrl_in,
                            int nbatch,
"""
    s += ",\n".join(f"                            hls::stream<axis32_t> &aie_in_{r}"
                    for r in range(NUM_ROWS))
    s += ") {\n"
    s += "#pragma HLS interface m_axi port=batch_in bundle=gmem_in   offset=slave depth=" \
         f"{RING * NUM_ROWS * BUF_SIZE}\n"
    s += "#pragma HLS interface m_axi port=ctrl_in  bundle=gmem_ctrl offset=slave depth=16\n"
    for r in range(NUM_ROWS):
        s += f"#pragma HLS interface axis port=aie_in_{r}\n"
    s += "#pragma HLS interface s_axilite port=batch_in bundle=control\n"
    s += "#pragma HLS interface s_axilite port=ctrl_in  bundle=control\n"
    s += "#pragma HLS interface s_axilite port=nbatch   bundle=control\n"
    s += "#pragma HLS interface s_axilite port=return   bundle=control\n"
    s += """
    for (int b = 0; b < nbatch; b++) {
        wait_doorbell(ctrl_in, b + 1);
        process_batch(batch_in + (b % RING) * NUM_ROWS * BUF_SIZE,
"""
    s += ",\n".join(f"                      aie_in_{r}" for r in range(NUM_ROWS))
    s += ");\n    }\n}\n"
    return s


def collect_server():
    s = HEADER.format(buf=BUF_SIZE, score=SCORE_BUF, rows=NUM_ROWS,
                      cols=NUM_COLS, ring=RING)
    s += """
// One receiver per column: drain its AIE output stream into its buffer.
static void recv_col(hls::stream<axis32_t> &s, int buf[SCORE_BUF]) {
    for (int i = 0; i < SCORE_BUF; i++) {
#pragma HLS pipeline II=1
        buf[i] = s.read().data;
    }
}

// One m_axi writer: push all column buffers for this batch out to DDR.
static void store_all(const int buf[NUM_COLS][SCORE_BUF], int *scores_slot) {
    for (int c = 0; c < NUM_COLS; c++)
        for (int i = 0; i < SCORE_BUF; i++) {
#pragma HLS pipeline II=1
            scores_slot[c * SCORE_BUF + i] = buf[c][i];
        }
}

// Process exactly one batch: drain 50 column streams, store the slot to DDR.
static void process_batch(
"""
    s += ",\n".join(f"                          hls::stream<axis32_t> &aie_out_{c}"
                    for c in range(NUM_COLS))
    s += ",\n                          int *scores_slot) {\n#pragma HLS dataflow\n"
    s += "    int buf[NUM_COLS][SCORE_BUF];\n"
    s += "#pragma HLS array_partition variable=buf dim=1 type=complete\n\n"
    for c in range(NUM_COLS):
        s += f"    recv_col(aie_out_{c}, buf[{c}]);\n"
    s += "    store_all(buf, scores_slot);\n}\n"

    s += """
extern "C" void collect_server(int *scores_out,
                               volatile int *ctrl_out,
                               int nbatch,
"""
    s += ",\n".join(f"                               hls::stream<axis32_t> &aie_out_{c}"
                    for c in range(NUM_COLS))
    s += ") {\n"
    s += "#pragma HLS interface m_axi port=scores_out bundle=gmem_out      offset=slave depth=" \
         f"{RING * NUM_COLS * SCORE_BUF}\n"
    s += "#pragma HLS interface m_axi port=ctrl_out   bundle=gmem_ctrlout offset=slave depth=16\n"
    for c in range(NUM_COLS):
        s += f"#pragma HLS interface axis port=aie_out_{c}\n"
    s += "#pragma HLS interface s_axilite port=scores_out bundle=control\n"
    s += "#pragma HLS interface s_axilite port=ctrl_out   bundle=control\n"
    s += "#pragma HLS interface s_axilite port=nbatch     bundle=control\n"
    s += "#pragma HLS interface s_axilite port=return     bundle=control\n"
    s += """
    for (int b = 0; b < nbatch; b++) {
        process_batch(
"""
    s += ",\n".join(f"            aie_out_{c}" for c in range(NUM_COLS))
    s += ",\n            scores_out + (b % RING) * NUM_COLS * SCORE_BUF);\n"
    s += "        ctrl_out[0] = b + 1;   // publish completion (volatile -> real m_axi write)\n"
    s += "    }\n}\n"
    return s


if __name__ == "__main__":
    with open("dist_server.cpp", "w") as f:
        f.write(dist_server())
    with open("collect_server.cpp", "w") as f:
        f.write(collect_server())
    print(f"generated resident dist_server.cpp ({NUM_ROWS} streams) "
          f"and collect_server.cpp ({NUM_COLS} streams), RING={RING}")
